/**
 * Independent numeric verification of the sequences lessons (geometric sequences only — 2026 מיקוד).
 * Every answer is recomputed by generating the sequence term by term (repeated multiplication, iterating the
 * recursion rule, year-by-year / dose-by-dose / bounce-by-bounce simulation) and summing in a loop — never with the
 * closed-form S_n or S = a1/(1-q) formulas used in the solutions. Infinite sums are long truncations (4000 terms;
 * every convergent ratio here has |q| <= 0.95 inside the search ranges, so the neglected tail is below 1e-80).
 * Unknown parameters (q, x, k, number of terms) are found numerically — findRoots on the defining condition of the
 * statement, with a1 obtained by scaling a sequence that starts at 1 — or by brute force over n, and the resulting
 * model is checked against every given of the statement.
 */
