const ex = (id: string) => Object.values(sequencesContent).flatMap((lesson) => lesson.exercises).find((e) => e.id === id)!;

/** Compares the authored answers (in order) with independently computed values, to `digits` relative digits. */
function expectAnswers(id: string, computed: number[], digits = 8) {
  const answers = ex(id).answers ?? [];
  expect(answers.length, `${id}: number of answers`).toBe(computed.length);
  answers.forEach((answer, index) => {
    const scale = Math.max(1, Math.abs(computed[index]));
    expect(answer.value / scale, `${id}: ${answer.label}`).toBeCloseTo(computed[index] / scale, digits);
  });
}

const LONG = 4000;

/** The first n terms a1, a1·q, a1·q², … generated by repeated multiplication. */
function terms(a1: number, q: number, n: number): number[] {
  const out: number[] = [];
  let current = a1;
  for (let i = 0; i < n; i += 1) {
    out.push(current);
    current *= q;
  }
  return out;
}

/** The first n terms of the sequence defined by a1 and the recursion rule a_{n+1} = rule(a_n). */
function iterate(a1: number, rule: (value: number) => number, n: number): number[] {
  const out: number[] = [];
  let current = a1;
  for (let i = 0; i < n; i += 1) {
    out.push(current);
    current = rule(current);
  }
  return out;
}

function sum(values: number[]): number {
  return values.reduce((total, value) => total + value, 0);
}

/** Truncated infinite sum (4000 terms). */
function infiniteSum(a1: number, q: number): number {
  return sum(terms(a1, q, LONG));
}

/** Terms in odd places a1, a3, a5, … and in even places a2, a4, … */
const oddPlaces = (values: number[]) => values.filter((_, index) => index % 2 === 0);
const evenPlaces = (values: number[]) => values.filter((_, index) => index % 2 === 1);

/** Asserts that consecutive ratios are all equal and returns that ratio. */
function commonRatio(values: number[]): number {
  const ratio = values[1] / values[0];
  for (let i = 1; i < values.length; i += 1) expect(values[i] / values[i - 1]).toBeCloseTo(ratio, 9);
  return ratio;
}

/** Roots of f on [lo, hi] with a small neighbourhood of 0 removed (q = 0 is never a ratio of a geometric sequence). */
function rootsAwayFromZero(f: (q: number) => number, lo: number, hi: number, steps = 4000): number[] {
  const negative = lo < 0 ? findRoots(f, lo, Math.min(hi, -1e-3), steps) : [];
  const positive = hi > 0 ? findRoots(f, Math.max(lo, 1e-3), hi, steps) : [];
  return [...negative, ...positive];
}

/** x-values for which three expressions form three consecutive terms of a geometric sequence (equal ratios). */
function geometricTripleRoots(f1: (x: number) => number, f2: (x: number) => number, f3: (x: number) => number, lo: number, hi: number): number[] {
  const gap = (x: number) => f2(x) / f1(x) - f3(x) / f2(x);
  // Sign changes at the poles of the ratios are discarded: only true zeros of the gap remain.
  return findRoots(gap, lo, hi).filter((x) => Math.abs(gap(x)) < 1e-6);
}

/** Smallest n >= 1 with predicate(n). */
function firstIndex(predicate: (n: number) => boolean, max = 10000): number {
  for (let n = 1; n <= max; n += 1) if (predicate(n)) return n;
  throw new Error('no index found');
}

