    const increasing = candidates.filter(({ a1, q }) => isIncreasing(terms(a1, q, 10)));
    expect(increasing).toHaveLength(1);
    const { a1, q } = increasing[0];
    const t = terms(a1, q, 10);
    expect(t[1] * t[3]).toBeCloseTo(256, 8);
    const n = firstIndex((k) => sum(terms(a1, q, k)) >= 1365 - 1e-6);
    expect(sum(terms(a1, q, n))).toBeCloseTo(1365, 6);
    expectAnswers('seq-review-b-1', [t[2], a1, q, n]);
